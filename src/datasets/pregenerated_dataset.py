import torch
import pandas as pd
from torch.utils.data import Dataset
from pathlib import Path
import json
import os
class PreGeneratedDataset(Dataset):
    def __init__(self, root_dir, num_samples=None, load_metadata=False, ignore_csv="ignore_files.csv"):
        """
        A fast dataset loader for data pre-generated by generate_dataset.py.

        Args:
            root_dir (str): The path to the 'train' or 'val' directory, which
                            must contain a 'metadata.csv' file.
            load_metadata (bool): If True, loads the detailed .json metadata file
                                  for each sample. Set to False for maximum training
                                  speed if metadata is not needed.
        """
        super().__init__()
        self.root_path = Path(root_dir)
        self.sample_dir = os.path.join(root_dir, "samples")
        self.load_metadata = load_metadata
        ignore_path = Path(ignore_csv)
        if ignore_path.exists():
            df = pd.read_csv(ignore_path)
            # CSV expected to contain: filename
            self.ignore_files = set(df["filename"].astype(str).tolist())
        else:
            self.ignore_files = set()
        all_files = [
            f for f in os.listdir(self.sample_dir)
            if f.endswith(".pt")
        ]
        self.files = [f for f in all_files if f not in self.ignore_files]
        # Load the main metadata index that points to all the sample files
        # metadata_path = self.root_path / "metadata.csv"
        # if not metadata_path.exists():
        #     raise FileNotFoundError(f"Could not find metadata.csv in {root_dir}")
        # self.metadata_index = pd.read_csv(metadata_path)
        
        self.files.sort(key=lambda x: int(os.path.splitext(x)[0]))
        if num_samples is not None:
            self.files = self.files[:num_samples]

    def __len__(self):
        return len(self.files)

    def __getitem__(self, idx):
        file_path = os.path.join(self.sample_dir, self.files[idx])
        data = torch.load(file_path, weights_only=False)
        data['dataset_name'] = 'SyntheticHomography'
        data.pop('semantic0', None)
        data.pop('semantic1', None)
        data['filename'] = self.files[idx]
        return data